package bookmarks

import (
	"context"
	"crypto/sha256"
	"encoding/json"
	"errors"

	"github.com/jackc/pgx/v5"
)

var ErrConflict = errors.New("bookmark changed")
var ErrOperationReused = errors.New("operation reused with different payload")

type State struct {
	Entry
	Revision int64 `json:"revision"`
	Deleted  bool  `json:"deleted"`
}
type Change struct {
	OperationID      string `json:"operationId"`
	ExpectedRevision int64  `json:"expectedRevision"`
	Bookmark         Entry  `json:"bookmark"`
	Deleted          bool   `json:"deleted"`
}
type syncReceipt struct {
	Kind        string `json:"kind"`
	Fingerprint []byte `json:"fingerprint"`
	Bookmark    State  `json:"bookmark"`
}

// State includes tombstones so an old device cannot silently resurrect deletes.
func (s Postgres) State(ctx context.Context, owner string) ([]State, error) {
	rows, err := s.Pool.Query(ctx, `SELECT book_id,book_version,locator,server_revision,deleted_at IS NOT NULL FROM bookmarks WHERE user_id=$1 ORDER BY book_id,book_version,locator->>'paragraph'`, owner)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	result := make([]State, 0)
	for rows.Next() {
		var entry State
		var book, version string
		var raw []byte
		if err := rows.Scan(&book, &version, &raw, &entry.Revision, &entry.Deleted); err != nil {
			return nil, err
		}
		if err := json.Unmarshal(raw, &entry.Entry); err != nil {
			return nil, err
		}
		entry.BookID, entry.Version = book, version
		result = append(result, entry)
	}
	return result, rows.Err()
}

// Apply shares the owner lock with guest import. The mutation and receipt must
// commit together; a retry returns its original result, never reapplies a write.
func (s Postgres) Apply(ctx context.Context, owner string, change Change) (State, error) {
	tx, err := s.Pool.Begin(ctx)
	if err != nil {
		return State{}, err
	}
	defer tx.Rollback(ctx)
	var user string
	if err = tx.QueryRow(ctx, `SELECT id::text FROM users WHERE id=$1 AND deleted_at IS NULL FOR UPDATE`, owner).Scan(&user); err != nil {
		return State{}, err
	}
	encoded, err := json.Marshal(change)
	if err != nil {
		return State{}, err
	}
	fingerprint := sha256.Sum256(encoded)
	var raw []byte
	err = tx.QueryRow(ctx, `SELECT result FROM processed_operations WHERE user_id=$1 AND operation_id=$2`, owner, change.OperationID).Scan(&raw)
	if err == nil {
		var stored syncReceipt
		if err = json.Unmarshal(raw, &stored); err != nil {
			return State{}, err
		}
		if stored.Kind != "bookmark.apply.v1" || string(stored.Fingerprint) != string(fingerprint[:]) {
			return State{}, ErrOperationReused
		}
		return stored.Bookmark, nil
	}
	if !errors.Is(err, pgx.ErrNoRows) {
		return State{}, err
	}
	entry := change.Bookmark
	id := entryID(owner, entry)
	var revision int64
	// Natural identity also covers IDs generated by earlier clients.
	err = tx.QueryRow(ctx, `SELECT id::text,server_revision FROM bookmarks WHERE user_id=$1 AND book_id=$2 AND book_version=$3 AND locator->>'paragraph'=$4`, owner, entry.BookID, entry.Version, entry.Paragraph).Scan(&id, &revision)
	if err != nil && !errors.Is(err, pgx.ErrNoRows) {
		return State{}, err
	}
	if revision != change.ExpectedRevision {
		return State{}, ErrConflict
	}
	locator, err := json.Marshal(entry)
	if err != nil {
		return State{}, err
	}
	result := State{Entry: entry, Revision: revision + 1, Deleted: change.Deleted}
	// Deleting an absent bookmark still records a tombstone (revision 1).
	_, err = tx.Exec(ctx, `INSERT INTO bookmarks(id,user_id,book_id,book_version,locator,server_revision,deleted_at)
 VALUES($1,$2,$3,$4,$5,$6,CASE WHEN $7 THEN now() ELSE NULL END)
 ON CONFLICT(id) DO UPDATE SET locator=excluded.locator,server_revision=excluded.server_revision,deleted_at=excluded.deleted_at`, id, owner, entry.BookID, entry.Version, locator, result.Revision, change.Deleted)
	if err != nil {
		return State{}, err
	}
	stored, err := json.Marshal(syncReceipt{Kind: "bookmark.apply.v1", Fingerprint: fingerprint[:], Bookmark: result})
	if err != nil {
		return State{}, err
	}
	if _, err = tx.Exec(ctx, `INSERT INTO processed_operations(user_id,operation_id,result) VALUES($1,$2,$3)`, owner, change.OperationID, stored); err != nil {
		return State{}, err
	}
	if err = tx.Commit(ctx); err != nil {
		return State{}, err
	}
	return result, nil
}
